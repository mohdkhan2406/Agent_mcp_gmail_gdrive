import react from '@vitejs/plugin-react'
import { defineConfig } from 'vite'

// https://vite.dev/config/
export default defineConfig({
  plugins: [react()],

  server: {
    // The app calls /api/query. In dev, Vite forwards that to the
    // FastAPI server; in the container, nginx does the same job.
    // Either way the browser sees one origin, so CORS never applies.
    proxy: {
      '/api': {
        target: 'http://127.0.0.1:8000',
        changeOrigin: true,
        rewrite: (path) => path.replace(/^\/api/, ''),
      },
    },
  },
})
